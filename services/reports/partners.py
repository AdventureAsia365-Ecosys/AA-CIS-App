def step_times(s: dict) -> dict[str, Optional[datetime]]:
    return {"created": _ts(s["created_at"]), "member": _ts(s.get("member_at")), "brief": _ts(s.get("brief_at")),
            "approved": _ts(s.get("approved_at")), "publish": _ts(s.get("publish_at"))}


def funnel(steps: list[dict], first: date, last: date, stuck_days: Optional[int], as_of: datetime) -> dict:
    """Content studio funnel: per step the partners that reached it by the end and during the period, median days
    per step by sign-up month, time to first value and the stuck list. Pure."""
    start, end = bounds(first, last)
    reached = {k: 0 for k, _ in STEPS}
    during = {k: 0 for k, _ in STEPS}
    cohorts: dict[str, dict[str, list[float]]] = {}
    ttv, stuck, gaps = [], [], []
    for s in steps:
        t = step_times(s)
        for k, _label in STEPS:
            if t[k] is not None:
                reached[k] += 1
                during[k] += int(start <= t[k] < end)
        month = t["created"].strftime("%Y-%m")
        c = cohorts.setdefault(month, {"partners": [], **{k: [] for k, _ in STEPS[1:]}})
        c["partners"].append(1.0)
        prev = t["created"]
        for k, _label in STEPS[1:]:
            if t[k] is None:
                break
            c[k].append(round(max(0.0, (t[k] - prev).total_seconds()) / 86400, 1))
            prev = t[k]
        if t["publish"] is not None:
            ttv.append(round((t["publish"] - t["created"]).total_seconds() / 86400, 1))
            continue
        if not s.get("has_seo_config"):
            gaps.append(short(s["tenant_id"]))
        if s.get("account_status") in ("closed", "offboarding") or stuck_days is None:
            continue
        last_key = max((k for k, _ in STEPS if t[k] is not None), key=lambda k: t[k])
        idle = (as_of - t[last_key]).total_seconds() / 86400
        if idle > stuck_days:
            nxt = next(label for k, label in STEPS if t[k] is None)
            stuck.append({"partner": short(s["tenant_id"]), "product": "content", "at": dict(STEPS)[last_key],
                          "waiting_for": nxt, "days": int(idle)})
    by_month = [{"month": m, "partners": len(c["partners"]),
                 **{k: (median(c[k]) if c[k] else None) for k, _ in STEPS[1:]},
                 **{f"{k}_n": len(c[k]) for k, _ in STEPS[1:]}} for m, c in sorted(cohorts.items())]
    return {"partners": len(steps), "reached": reached, "during": during, "by_month": by_month,
            "ttv_median_days": median(ttv) if ttv else None, "ttv_n": len(ttv), "stuck": stuck,
            "no_seo_config": gaps}


def crm_funnel(inputs: Optional[dict], stuck_days: Optional[int], as_of: datetime) -> dict:
    ag = crm_part(inputs, "agencies")
    if failed(ag):
        return {"error": failed(ag)}
    rows = [a for a in ag.get("rows") or [] if a.get("state") != "offboarded"]
    stuck = []
    for a in rows:
        created = _ts(a.get("created_at"))
        if a.get("state") != "active" or a.get("has_owner") or created is None or stuck_days is None:
            continue
        idle = (as_of - created).total_seconds() / 86400
        if idle > stuck_days:
            stuck.append({"partner": short(a["tenant_id"]), "product": "crm", "at": "Agency created",
                          "waiting_for": "Active owner", "days": int(idle),
                          "synthetic": bool(a.get("is_synthetic"))})
    return {"agencies": len(rows), "synthetic": sum(1 for a in rows if a.get("is_synthetic")),
            "with_owner": sum(1 for a in rows if a.get("has_owner")), "stuck": stuck}


def ex07_kpis(fn: dict, crm: dict, act: dict, th: dict) -> list[dict]:
    if "error" in fn:
        why = f"not readable: {fn['error']}"
        acts = _kpi_line("K-PART-ACT", None, "no_data", why)
        ttv = _kpi_line("K-ONB-TTV", None, "no_data", why)
        stuck = _kpi_line("K-ONB-STUCK", None, "no_data", why)
    else:
        acts = (_kpi_line("K-PART-ACT", None, "no_data", _missing_note(th, "activation_days"))
                if th.get("activation_days") is None else
                _kpi_line("K-PART-ACT", act["rate"], "info",
                          f"every partner so far: {act['activated']} of {act['cohort']} published within "
                          f"{_n(th['activation_days'])} days ({act['complete']} with the window closed)"))
        ttv = _kpi_line("K-ONB-TTV", fn["ttv_median_days"], "info",
                        f"median days from creation to first publish over {fn['ttv_n']} partner(s); CRM first "
                        f"proposal {NOT_PUBLISHED}")
        if th.get("stuck_days") is None:
            stuck = _kpi_line("K-ONB-STUCK", None, "no_data", _missing_note(th, "stuck_days"))
        else:
            crm_stuck = crm.get("stuck", []) if "error" not in crm else []
            n = len(fn["stuck"]) + len(crm_stuck)
            stuck = _kpi_line("K-ONB-STUCK", float(n), "amber" if n else "ok",
                              f"more than {_n(th['stuck_days'])} days on one step (Platform › Settings): content "
                              f"{len(fn['stuck'])}, CRM "
                              + (str(len(crm_stuck)) if "error" not in crm else "not read"))
    return [acts,
            _kpi_line("K-ONB-CRM", None, "no_data",
                      f"{NOT_PUBLISHED}: proposals are CRM business data, crm.ops.v1 carries none"),
            ttv, stuck]


