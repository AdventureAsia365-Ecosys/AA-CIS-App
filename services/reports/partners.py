TENANTS_SQL = """
    SELECT tenant_id::text AS tenant_id, kind, account_status, coalesce(is_canary, false) AS is_canary, is_pilot,
           created_at, cancelled_at, cancellation_reason IS NOT NULL AS has_reason
      FROM shared.tenants
     ORDER BY tenant_id
"""
SUBSCRIPTIONS_SQL = """
    SELECT tenant_id::text AS tenant_id, product, plan_key, status, seats, started_at, canceled_at, trial_ends_at
      FROM shared.tenant_subscription
     ORDER BY tenant_id, product
"""
PLANS_SQL = """
    SELECT plan_key, product, price_usd_monthly::float AS price, price_unit, seats_included,
           price_extra_seat_usd::float AS extra_seat
      FROM shared.plan
"""
REWRITES_SQL = """
    SELECT tenant_id::text AS tenant_id, year_month, rewrite_count
      FROM shared.tenant_rewrite_usage
     WHERE year_month = ANY($1::text[])
"""
# The onboarding steps of every partner (agency, not a canary) up to $1 (exclusive): the first time each was reached.
# A brand brief is the oldest brand rules row (one row per version; updated_at, NOT NULL: created_at is not on every
# database).
STEPS_SQL = """
    SELECT t.tenant_id::text AS tenant_id, t.account_status, t.created_at,
           (SELECT min(e.occurred_at) FROM shared.tenant_membership_event e
             WHERE e.tenant_id = t.tenant_id AND e.type = 'membership.activated' AND e.occurred_at < $1) AS member_at,
           (SELECT min(b.updated_at) FROM shared.tenant_brand_rules b
             WHERE b.tenant_id = t.tenant_id AND b.updated_at < $1) AS brief_at,
           (SELECT min(p.created_at) FROM acp_shared.content_piece p
             WHERE p.tenant_id = t.tenant_id AND p.status = 'approved' AND p.created_at < $1) AS approved_at,
           (SELECT min(l.published_at) FROM acp_shared.publish_log l
             WHERE l.tenant_id = t.tenant_id AND l.published_at IS NOT NULL AND l.published_at < $1) AS publish_at,
           EXISTS (SELECT 1 FROM shared.tenant_seo_config s WHERE s.tenant_id = t.tenant_id) AS has_seo_config
      FROM shared.tenants t
     WHERE t.kind = 'agency' AND NOT coalesce(t.is_canary, false) AND t.created_at < $1
     ORDER BY t.tenant_id
"""


async def _rows(conn, sql: str, *args) -> list[dict]:
    return [dict(r) for r in await conn.fetch(sql, *args)]


async def quotas(conn, tenant_ids: list[str]) -> dict:
    """{tenant_id: the monthly rewrite quota the API enforces now} (api/routers/v1_tours._get_tenant_plan_limit: the
    resolved content.rewrite entitlement, an override, else the membership plan)."""
    from api.routers import v1_tours     # lazy: the router module is heavy and only this part needs it

    return {tid: (await v1_tours._get_tenant_plan_limit(conn, tid))[1] for tid in tenant_ids}


def months_back(last: date, n: int) -> list[str]:
    """The `n` year-months ending with the month of `last`, oldest first ("YYYY-MM")."""
    y, m = last.year, last.month
    out = []
    for _ in range(max(1, n)):
        out.append(f"{y:04d}-{m:02d}")
        y, m = (y - 1, 12) if m == 1 else (y, m - 1)
    return out[::-1]


def partner_ids(tenants: list[dict]) -> set[str]:
    return {t["tenant_id"] for t in tenants if t.get("kind") == "agency" and not t.get("is_canary")}


async def collect_ex03(conn, first: date, last: date, th: dict) -> dict:
    _start, end = bounds(first, last)
    months = months_back(last, int(th.get("low_use_months") or 1))
    facts = await src.run_parts({
        "tenants": lambda: _rows(conn, TENANTS_SQL),
        "subscriptions": lambda: _rows(conn, SUBSCRIPTIONS_SQL),
        "plans": lambda: _rows(conn, PLANS_SQL),
        "rewrites": lambda: _rows(conn, REWRITES_SQL, months),
        "steps": lambda: _rows(conn, STEPS_SQL, end),
    })
    ids = sorted(partner_ids(facts["tenants"])) if isinstance(facts.get("tenants"), list) else []
    facts["quotas"] = (await src.run_parts({"quotas": lambda: quotas(conn, ids)}))["quotas"]
    facts["months"] = months
    return facts


async def collect_ex07(conn, first: date, last: date) -> dict:
    _start, end = bounds(first, last)
    return await src.run_parts({"steps": lambda: _rows(conn, STEPS_SQL, end)})


