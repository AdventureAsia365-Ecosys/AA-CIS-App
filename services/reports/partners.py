    if "error" in crm:
        return out + [f"- Not readable: {crm['error']}", ""]
    cov = crm.get("coverage")
    if cov:
        a, mb = cov.get("agencies") or {}, cov.get("members") or {}
        out += [f"- Agencies: active {a.get('active', 0)}, locked {a.get('locked', 0)}, offboarding "
                f"{a.get('offboarding', 0)}, offboarded {a.get('offboarded', 0)} (synthetic, any state: "
                f"{a.get('synthetic', 0)}). Members: active {mb.get('active', 0)}, invited {mb.get('invited', 0)}, "
                f"disabled {mb.get('disabled', 0)}.", ""]
