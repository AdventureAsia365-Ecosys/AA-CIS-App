def short(tenant_id: Any) -> str:
    return str(tenant_id or "")[:ID_PREFIX] or "—"


def bounds(first: date, last: date) -> tuple[datetime, datetime]:
    return datetime.combine(first, time(0), UTC), datetime.combine(last + timedelta(days=1), time(0), UTC)


def _ts(v: Any) -> Optional[datetime]:
    if isinstance(v, datetime):
        return v if v.tzinfo else v.replace(tzinfo=UTC)
    if isinstance(v, str) and v:
        try:
            d = datetime.fromisoformat(v.replace("Z", "+00:00"))
        except ValueError:
            return None
        return d if d.tzinfo else d.replace(tzinfo=UTC)
    return None


def _day(v: Any) -> Optional[str]:
    t = _ts(v)
    return t.date().isoformat() if t else None


def _n(v: Any) -> str:
    """A setting value in text: 80.0 -> "80", None -> "—"."""
    return "—" if v is None else f"{v:g}"


def _f(v: Any) -> Optional[float]:
    try:
        return None if v is None else float(v)
    except (TypeError, ValueError):
        return None


async def thresholds() -> dict:
    """The value in force of each R6 setting ({name: number}), and the keys that could not be resolved."""
    out: dict[str, Any] = {"missing": []}
    for name, key in SETTING_NAMES.items():
        try:
            out[name] = await settings.aget(key)
        except Exception:       # noqa: BLE001 — an unknown key (code before CIS 430) leaves its check out, named
            out[name] = None
            out["missing"].append(key)
    return out


def _missing_note(th: dict, *names: str) -> str:
    keys = [SETTING_NAMES[n] for n in names if th.get(n) is None]
    return f"setting not available ({', '.join(keys)})" if keys else ""


