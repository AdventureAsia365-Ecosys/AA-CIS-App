"""AA-1051 — the pre-registered verdict of a W5 proof from its result rows (shared.eval_item_result of the R2 runs the
proof queued). Pure: the rows come from runner.report.

Arms. A = the control of each item (the stored output re-judged, $0 writer: R2 mode rejudge); B = the candidate
(regenerated by the current writers or the candidate release, R2 arm candidate mode regenerate); A' = the repeat arm
(a second run of B's configuration on the noise sample), whose difference with B measures the run-to-run noise.

Per item metric (lower is better unless the pre-registration says higher):
  item_fail_rate          1 when the verdict is fail, else 0
  fail_claims_per_item    the number of unsupported claims the judge quoted (details.judge_claims; at most the
                          judge's MAX_CLAIMS, 8)
  fail_classes_per_item   the number of failure classes (failure_codes)

Decision (tightened from the audit sketch "mean(B - A) <= max(margin, 2 SE(A - A'))" to a one-sided bound, so it
matches the power check): d_i = B_i - A_i (signed so that positive = worse), n paired items,
  bound     = mean(d) + z_(1-alpha) * sd(d) / sqrt(n)
  allowance = max(margin_abs, noise_se_k * SE_noise), SE_noise = sd(A' - B) / sqrt(k) over the k noise items (0 without)
  non_inferior   bound <= allowance
  improve        mean(d) + z_(1-alpha) * SE < 0 and -mean(d) >= allowance (the margin is then the smallest
                 improvement that counts)
  else           inferior (non_inferior rule) / not_improved (improve rule)
`invalid` comes first when a requirement fails: fewer paired items than the fixed sample (paired_all), more than
max_mixed_judges judge identities beyond one, more than max_hard_stop_1 hard stops of class 1, or an arm whose run is
missing.
"""
from __future__ import annotations

import math
from statistics import NormalDist, mean, median, stdev
from typing import Iterable, Optional


def metric_of(row: dict, metric: str) -> Optional[float]:
    """One result row's value of a paired metric; None for an error / skipped row."""
    if row.get("verdict") not in ("pass", "fail"):
        return None
    if metric == "item_fail_rate":
        return 1.0 if row["verdict"] == "fail" else 0.0
    if metric == "fail_claims_per_item":
        return float(len((row.get("details") or {}).get("judge_claims") or []))
    if metric == "fail_classes_per_item":
        return float(len(row.get("failure_codes") or []))
    raise ValueError(f"not a paired metric: {metric}")


def arms_by_sample(rows: Iterable[dict]) -> dict[str, dict[str, dict]]:
    """{sample_id: {"A": control row, "B": candidate row}} of ONE run's result rows (rows carry sample_id)."""
    out: dict[str, dict[str, dict]] = {}
    for r in rows:
        sid = r.get("sample_id")
        if not sid:
            continue
        if r.get("arm") == "control" and r.get("mode") in ("rejudge", "regenerate"):
            out.setdefault(sid, {})["A"] = r
        elif r.get("arm") == "candidate" and r.get("mode") == "regenerate":
            out.setdefault(sid, {})["B"] = r
    return out


def _signed(v: float, direction: str) -> float:
    return v if direction == "lower" else -v


def _sd(xs: list[float]) -> float:
    return stdev(xs) if len(xs) >= 2 else 0.0


def decide(doc: dict, b_rows: list[dict], *, a_prime_rows: Optional[list[dict]] = None,
           run_details: Optional[dict] = None) -> dict:
    """The verdict of a pre-registration (`doc`) from the B run's rows (which hold A as its control rows) and the A'
    run's rows. `run_details`: the B run's prompt_eval_runs.details (judge identities, hard stops)."""
    dec = doc["decision"]
    metric = dec["metric"]
    direction = next(m["direction"] for m in doc["metrics"] if m["name"] == metric)
    req = {"paired_all": True, "max_mixed_judges": 0, "max_hard_stop_1": 0, **(doc.get("requirements") or {})}
    sample = list(doc.get("sample_ids") or [])
    by = arms_by_sample(b_rows)
    diffs, a_vals, b_vals = [], [], []
    for sid in sample:
        pair = by.get(sid) or {}
        a = metric_of(pair["A"], metric) if "A" in pair else None
        b = metric_of(pair["B"], metric) if "B" in pair else None
        if a is None or b is None:
            continue
        a_vals.append(a)
        b_vals.append(b)
        diffs.append(_signed(b - a, direction))
    noise: list[float] = []
    if a_prime_rows:
        ap = arms_by_sample(a_prime_rows)
        for sid in doc.get("noise_sample_ids") or []:
            x = metric_of(ap[sid]["B"], metric) if "B" in (ap.get(sid) or {}) else None
            y = metric_of(by[sid]["B"], metric) if "B" in (by.get(sid) or {}) else None
            if x is not None and y is not None:
                noise.append(_signed(x - y, direction))
    problems: list[str] = []
    n = len(diffs)
    if not b_rows:
        problems.append("the B run has no result rows")
    if req["paired_all"] and n < len(sample):
        problems.append(f"paired {n} of the {len(sample)} pre-registered items")
    details = run_details or {}
    identities = details.get("judge_identities") or []
    if len(identities) - 1 > int(req["max_mixed_judges"]):
        problems.append(f"{len(identities)} judge identities (mixed judges)")
    hs1 = int(((details.get("counts") or {}).get("hard_stops") or {}).get("1", 0))
    if hs1 > int(req["max_hard_stop_1"]):
        problems.append(f"{hs1} hard stops of class 1 (a new hard fact class)")
    if doc.get("noise_sample_ids") and not noise:
        problems.append("the A' noise arm has no paired rows")
    z = NormalDist().inv_cdf(1 - float(dec["alpha"]))
    m_d = mean(diffs) if diffs else None
    se = _sd(diffs) / math.sqrt(n) if n else None
    se_noise = _sd(noise) / math.sqrt(len(noise)) if noise else 0.0
    k = float(dec["noise_se_k"])
    allowance = max(float(dec["margin_abs"]), k * se_noise)
    bound = (m_d + z * se) if m_d is not None else None
    if problems:
        verdict = "invalid"
    elif dec["rule"] == "non_inferior":
        verdict = "non_inferior" if bound <= allowance + 1e-12 else "inferior"
    else:
        verdict = "improve" if (bound < 0 and -m_d >= allowance) else "not_improved"
    return {"verdict": verdict, "rule": dec["rule"], "metric": metric, "direction": direction, "paired": n,
            "planned": len(sample), "mean_a": _r(mean(a_vals)) if a_vals else None,
            "mean_b": _r(mean(b_vals)) if b_vals else None, "mean_diff": _r(m_d), "se_diff": _r(se),
            "upper_bound": _r(bound), "margin_abs": float(dec["margin_abs"]), "noise_items": len(noise),
            "se_noise": _r(se_noise), "allowance": _r(allowance), "problems": problems}


def _r(v: Optional[float]) -> Optional[float]:
    return None if v is None else round(v, 6)


def targets(doc: dict, computed: dict[str, Optional[float]]) -> list[dict]:
    """Each metric with a target: met / missed / pending (external, or not computed). `computed`: name -> value."""
    out = []
    for m in doc.get("metrics") or []:
        t = m.get("target")
        if not t:
            continue
        v = computed.get(m["name"]) if m.get("kind") == "computed" else None
        if v is None:
            out.append({"metric": m["name"], "target": t, "value": None, "status": "pending"})
            continue
        ok = {"<=": v <= t["value"], ">=": v >= t["value"], "==": v == t["value"]}[t["op"]]
        out.append({"metric": m["name"], "target": t, "value": v, "status": "met" if ok else "missed"})
    return out


def computed_metrics(b_rows: list[dict], per_object: Optional[dict] = None) -> dict[str, Optional[float]]:
    """The arm-B values of the computed metrics: rates over the candidate rows with a verdict, and the cost /
    requests medians per object from cost_report.attribute (`per_object`: {result_id: {cost_usd, requests,
    writer_requests}})."""
    cand = [r for r in b_rows if r.get("arm") == "candidate" and r.get("mode") == "regenerate"
            and r.get("verdict") in ("pass", "fail")]
    out: dict[str, Optional[float]] = {k: None for k in (
        "item_fail_rate", "fail_claims_per_item", "fail_classes_per_item", "first_pass_yield", "hard_stops",
        "cost_per_object_usd", "requests_per_object", "writer_requests_per_object")}
    if cand:
        out["item_fail_rate"] = _r(mean(metric_of(r, "item_fail_rate") for r in cand))
        out["first_pass_yield"] = _r(1 - out["item_fail_rate"])
        out["fail_claims_per_item"] = _r(mean(metric_of(r, "fail_claims_per_item") for r in cand))
        out["fail_classes_per_item"] = _r(mean(metric_of(r, "fail_classes_per_item") for r in cand))
        out["hard_stops"] = float(sum(1 for r in cand if r.get("hard_stop")))
    if per_object:
        objs = [per_object[str(r["result_id"])] for r in cand if str(r.get("result_id")) in per_object]
        if objs:
            out["cost_per_object_usd"] = _r(median(o["cost_usd"] for o in objs))
            out["requests_per_object"] = float(median(o["requests"] for o in objs))
            out["writer_requests_per_object"] = float(median(o["writer_requests"] for o in objs))
    return out


__all__ = ["arms_by_sample", "computed_metrics", "decide", "metric_of", "targets"]
