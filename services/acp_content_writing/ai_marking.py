"""
services.acp_content_writing.ai_marking — AA-1040: the machine-readable mark of AI-generated content (EU AI Act
Art. 50(2), root ADR 0019 d19).

Every `acp_shared.content_piece` row is written by the T9 writer model, so every piece is AI-generated by
construction; what this module adds is a mark other software can read:

- **stored:** `content_piece.writer_input -> 'ai_provenance'` (a JSON key in an existing column, no migration):
  `{"ai_generated": true, "generator": ..., "model": <the writer model of the final attempt>, "generated_at": ...}`
  stamped when the piece is finalized, plus `human_edited_at` when the tenant edits the text (PATCH
  /v1/content-writing/pieces/{id}). A piece finalized before AA-1040 has no key: its mark is still `ai_generated`,
  `generated_at` = the row's `created_at`, `model` unknown (None);
- **in the tenant JSON:** `piece["ai"]` (`/v1/content-writing/pieces/*`, from :func:`piece_mark`);
- **in HTML:** the published / embedded fragment's `<article>` carries `data-ai-*` attributes (kept by WordPress for
  every user role: wp_kses allows `data-*` attributes since WP 5.0) followed by `<meta name="ai-*">` tags (kept when
  the connected WordPress user may post unfiltered HTML, i.e. administrators and editors; other roles' posts keep the
  attributes only); the downloaded standalone document carries the same `<meta>` tags in its `<head>`;
- **social posts:** none of the built channels' APIs has a label for a text post (Facebook Page feed); the mark
  stays in the piece and its publish record. Per-platform notes: root `docs/architecture/ai-use-register.md`.

The meta names are plain, self-describing names (`ai-generated`, `ai-generator`, `ai-model`, `ai-generated-at`,
`ai-human-edited`) plus the IPTC digital source type URI for content made by a trained model; there is no single
web standard for marking AI text yet, so the names are documented in the register rather than invented per caller.
"""
from __future__ import annotations

import html
import json
from datetime import datetime, timezone
from typing import Any, Optional

PROVENANCE_KEY = "ai_provenance"
GENERATOR = "Adventure Asia Content studio"
# The A-series Master catalog text (gold_aa_internal.published_tours aa_* columns) is written by the S1 writer model.
CATALOG_GENERATOR = "Adventure Asia catalog writer"
# The published_tours columns that hold that AI-written text; a tenant row carrying any of them gets the mark.
CATALOG_TEXT_FIELDS = frozenset({"aa_name", "aa_subtitle", "aa_summary", "aa_description", "aa_highlights",
                                 "aa_itineraries", "mobile_card_text"})
# IPTC NewsCodes digital source type: "created by a trained algorithmic model" (cv.iptc.org digitalsourcetype).
IPTC_DIGITAL_SOURCE_TYPE = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"
WRITER_STAGE = "t9_write"

# The writer model of the piece's final attempt: the newest billed t9_write ledger row of the request since the piece
# row was created (shadow calls excluded). Reads through idx_llm_call_log_stage_created (stage, created_at DESC).
WRITER_MODEL_SQL = """
    SELECT l.model
    FROM shared.llm_call_log l
    WHERE l.stage = $3
      AND l.created_at >= (SELECT cp.created_at FROM acp_shared.content_piece cp WHERE cp.piece_id = $2)
      AND l.angle_gate_request_id = $1
      AND (l.status IS NULL OR l.status IN ('ok', 'truncated'))
      AND l.is_shadow IS NOT TRUE
    ORDER BY l.created_at DESC
    LIMIT 1
"""

# AA-900 W0 (root ADR 0020, "stamp answered_model and fallback_used on every write"): the same ledger row, as one jsonb
# value: the answered model, whether a fallback rung answered, its route position and connection. The piece stores it
# admin-only in writer_input -> 'writer_answer' (ANSWER_KEY), next to the AI mark; the release KPIs read it there.
WRITER_ANSWER_SQL = """
    SELECT jsonb_build_object('answered_model', l.model, 'fallback_used', l.fallback_used,
                              'route_position', l.quality_signal -> 'route_position',
                              'connection_key', l.connection_key, 'effort', l.effort)
    FROM shared.llm_call_log l
    WHERE l.stage = $3
      AND l.created_at >= (SELECT cp.created_at FROM acp_shared.content_piece cp WHERE cp.piece_id = $2)
      AND l.angle_gate_request_id = $1
      AND (l.status IS NULL OR l.status IN ('ok', 'truncated'))
      AND l.is_shadow IS NOT TRUE
    ORDER BY l.created_at DESC
    LIMIT 1
"""
ANSWER_KEY = "writer_answer"


def _iso(value: Any) -> Optional[str]:
    if value is None:
        return None
    if isinstance(value, datetime):
        return value.isoformat()
    return str(value)


def stamp(model: Optional[str], generated_at: Optional[datetime] = None) -> dict:
    """The stored provenance of a freshly finalized piece."""
    return {
        "ai_generated": True,
        "generator": GENERATOR,
        "model": model or None,
        "generated_at": _iso(generated_at or datetime.now(timezone.utc)),
    }


def _as_dict(value: Any) -> dict:
    if isinstance(value, str):
        try:
            value = json.loads(value)
        except (TypeError, ValueError):
            return {}
    return value if isinstance(value, dict) else {}


def piece_mark(created_at: Any, provenance: Any = None) -> dict:
    """The mark of a piece, from its stored provenance (None or absent for a piece older than AA-1040).

    Always `ai_generated: True` (every content_piece is T9 output). `generated_at` falls back to the row's
    `created_at`; `model` is None when unknown. `human_edited` is True once the tenant edited the text."""
    prov = _as_dict(provenance)
    return {
        "ai_generated": True,
        "generator": prov.get("generator") or GENERATOR,
        "model": prov.get("model") or None,
        "generated_at": prov.get("generated_at") or _iso(created_at),
        "human_edited": bool(prov.get("human_edited_at")),
    }


def _attr(value: Any) -> str:
    return html.escape(str(value), quote=True)


def html_attributes(mark: dict) -> str:
    """` data-ai-generated="true" …` for the `<article>` tag (leading space included)."""
    parts = [("data-ai-generated", "true"), ("data-ai-generator", mark.get("generator") or GENERATOR)]
    if mark.get("model"):
        parts.append(("data-ai-model", mark["model"]))
    if mark.get("generated_at"):
        parts.append(("data-ai-generated-at", mark["generated_at"]))
    parts.append(("data-ai-human-edited", "true" if mark.get("human_edited") else "false"))
    return "".join(f' {name}="{_attr(value)}"' for name, value in parts)


def html_meta_tags(mark: dict) -> str:
    """The `<meta>` tags of the mark, on one line (no blank line, so WordPress's wpautop never wraps them one by
    one)."""
    tags = [("ai-generated", "true"), ("ai-generator", mark.get("generator") or GENERATOR)]
    if mark.get("model"):
        tags.append(("ai-model", mark["model"]))
    if mark.get("generated_at"):
        tags.append(("ai-generated-at", mark["generated_at"]))
    tags.append(("ai-human-edited", "true" if mark.get("human_edited") else "false"))
    tags.append(("digital-source-type", IPTC_DIGITAL_SOURCE_TYPE))
    return "".join(f'<meta name="{name}" content="{_attr(value)}">' for name, value in tags)


def response_headers(mark: dict) -> dict:
    """Headers of a download (text exports carry no markup, so the mark travels as headers)."""
    headers = {"X-AI-Generated": "true", "X-AI-Generator": mark.get("generator") or GENERATOR}
    if mark.get("model"):
        headers["X-AI-Model"] = str(mark["model"])
    return headers


def version_mark(edit_source: Optional[str], created_at: Any) -> dict:
    """The mark of a T2 tenant tour version (`tenant_tour_versions.edit_source` already records who wrote it):
    `ai_generated` / `re_rewrite` rows are a model's rewrite made at `created_at`; a `tenant_edit` row is a person's
    edit of earlier text (itself an AI rewrite of AI-written Master text), so it is AI-assisted and human-edited,
    with no generation time of its own."""
    edited = edit_source == "tenant_edit"
    return {
        "ai_generated": True,
        "generator": GENERATOR,
        "model": None,
        "generated_at": None if edited else _iso(created_at),
        "human_edited": edited,
    }


def tour_mark(updated_at: Any, published_at: Any = None) -> dict:
    """The mark of a tour's A-series Master catalog text (`published_tours.aa_*`, written by the S1 writer).

    `generated_at` is the last Master publish (`published_tours.updated_at`, moved only by a Master publish /
    promote, CIS 273), else the first (`published_at`). `model` is None: the writer model is recorded on
    `silver_aa_internal.generated_content`, which the tenant pool cannot read. `human_edited` is None (not known at
    this read): a staff edit before approval is recorded on `generated_content.human_edited`, also admin-side."""
    return {
        "ai_generated": True,
        "generator": CATALOG_GENERATOR,
        "model": None,
        "generated_at": _iso(updated_at) or _iso(published_at),
        "human_edited": None,
    }


def docx_properties(mark: dict) -> dict:
    """Core properties of a DOCX download (python-docx `core_properties`): keywords + comments carry the mark."""
    parts = [f"generator={mark.get('generator') or GENERATOR}"]
    if mark.get("model"):
        parts.append(f"model={mark['model']}")
    if mark.get("generated_at"):
        parts.append(f"generated-at={mark['generated_at']}")
    parts.append(f"human-edited={'true' if mark.get('human_edited') else 'false'}")
    return {"keywords": "ai-generated", "comments": "AI-generated content; " + "; ".join(parts)}


async def writer_model(conn, request_id, piece_id) -> Optional[str]:
    """Best-effort: the writer model of the piece's final attempt, or None (never raises)."""
    try:
        return await conn.fetchval(WRITER_MODEL_SQL, request_id, piece_id, WRITER_STAGE)
    except Exception:  # noqa: BLE001 — the mark must never fail a finalize
        return None


async def writer_answer(conn, request_id, piece_id) -> Optional[dict]:
    """Best-effort: {answered_model, fallback_used, route_position, connection_key, effort} of the piece's final
    writer attempt (the row writer_model reads), or None (no row, or the ledger is unreadable; never raises)."""
    try:
        raw = await conn.fetchval(WRITER_ANSWER_SQL, request_id, piece_id, WRITER_STAGE)
    except Exception:  # noqa: BLE001 — the stamp must never fail a finalize
        return None
    if isinstance(raw, str):
        try:
            raw = json.loads(raw)
        except ValueError:
            return None
    if not isinstance(raw, dict):
        return None
    out = {k: raw.get(k) for k in ("answered_model", "fallback_used", "route_position", "connection_key", "effort")}
    out["fallback_used"] = bool(out["fallback_used"]) or (isinstance(out["route_position"], int)
                                                         and out["route_position"] > 0)
    return out


