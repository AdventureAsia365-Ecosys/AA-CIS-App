"""Generate frontend/lib/quality-registry.generated.ts from the registry (AA-926):
`python -m services.quality.gen_frontend` (writes the files) or `--check` (exit 1 when one is stale).

The admin pages read gate labels and the retired set from that file, so the UI and the backend share one source. The
lint and a unit test fail when the file drifts. S279 lane L2: the pass line, the score colour bands and the SEO bands
are settings (Platform › Settings); the file no longer carries them (frontend/lib/qualityThresholds.ts reads them at
runtime from GET /admin/quality/thresholds).

AA-994: the Vietnamese gate labels (`label_vi` in taxonomy.yaml) go to the twin file
frontend/lib/quality-registry.generated.vi.ts (GATE_LABELS_VI, same keys, same order), the one place the
frontend i18n guard allows Vietnamese for this module; pages pick the map of the UI language."""
from __future__ import annotations

import json
import sys
from pathlib import Path

from services.quality import registry

OUT = Path(__file__).resolve().parents[2] / "frontend" / "lib" / "quality-registry.generated.ts"
OUT_VI = OUT.with_name("quality-registry.generated.vi.ts")


def render() -> str:
    labels = {n: g["label"] for n, g in registry.gates().items() if g.get("label")}
    retired = registry.retired_gates()
    lines = [
        "// GENERATED by `python -m services.quality.gen_frontend` from services/quality/{taxonomy,thresholds,"
        "writing_policy}.yaml",
        "// (AA-926, Quality System v1). Do not edit by hand: change the YAML and regenerate.",
        "",
        f"export const TAXONOMY_VERSION = {json.dumps(registry.TAXONOMY_VERSION)};",
        "",
        "/** Plain-language gate names for admins (the codes stay visible next to them). A labelled name is listed",
        " *  in the Content Quality gate filter. */",
        "export const GATE_LABELS: Record<string, string> = {",
        *[f"  {n}: {json.dumps(label, ensure_ascii=False)}," for n, label in labels.items()],
        "};",
        "",
        "/** AA-787 — gates the T10 stack no longer runs. Older pieces still carry them in their ledger, so the",
        " *  labels stay; the UI marks them retired and keeps them out of the main gate filter. */",
        "export const RETIRED_GATES: ReadonlySet<string> = new Set([",
        "  " + ", ".join(json.dumps(n) for n in retired) + ",",
        "]);",
        "",
        "// S279 lane L2: the pass line, the score colour bands and the SEO bands are settings of the platform",
        "// settings registry; the pages read them at runtime (lib/qualityThresholds.ts,",
        "// GET /admin/quality/thresholds).",
        "",
    ]
    return "\n".join(lines)


def render_vi() -> str:
    """The Vietnamese twin: GATE_LABELS_VI with the keys of GATE_LABELS (a labelled gate without label_vi keeps
    its English label, and the lint reports it)."""
    labels = {n: g.get("label_vi") or g["label"] for n, g in registry.gates().items() if g.get("label")}
    lines = [
        "// GENERATED by `python -m services.quality.gen_frontend` from services/quality/taxonomy.yaml (label_vi).",
        "// AA-994: the Vietnamese twin of quality-registry.generated.ts. Do not edit by hand: change the YAML and",
        "// regenerate.",
        "",
        "import type { GATE_LABELS } from \"./quality-registry.generated\";",
        "",
        "/** GATE_LABELS in Vietnamese: the same keys, in the same order. */",
        "export const GATE_LABELS_VI: Record<keyof typeof GATE_LABELS, string> = {",
        *[f"  {n}: {json.dumps(label, ensure_ascii=False)}," for n, label in labels.items()],
        "};",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    outputs = ((OUT, render()), (OUT_VI, render_vi()))
    if "--check" in argv:
        stale = [p for p, text in outputs if not (p.exists() and p.read_text(encoding="utf-8") == text)]
        for p in stale:
            print(f"stale: run python -m services.quality.gen_frontend ({p})")
        if not stale:
            print("fresh")
        return 1 if stale else 0
    for p, text in outputs:
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
