"""AA-992 — what the data coverage page shows: the sources (one query / listing / HTTP read each) and the rows (one
number each), in page order (design §1). Pure data: :mod:`.build` runs the sources and evaluates the rows.

A row reads its numbers with ``get(source, field)``; when that source failed, timed out or is not available yet the
row is ``na`` with the source's reason, and nothing is guessed. ``polarity`` says what "missing" means (critic B11):

- ``coverage``  missing = denominator − value (``atoms.tours``: live tours without atoms);
- ``defect``    missing = value, the denominator is context only (``atoms.older_than_master``);
- ``threshold`` missing = max(0, value − limit) (``paa.demand_age_days`` ≤ 30);
- ``equal``     missing = |denominator − value| (``tp.tours``: TripPlanner must serve exactly the live set).

``kind``: ``must`` (automatic; a gap above the expected one is a defect, red), ``backlog`` (needs a manual or paid run;
amber, names the issue), ``info`` (no target; grey). Status: ``ok`` (missing ≤ expected gap), ``gap``, ``info``, ``na``.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Callable, Literal, Optional

Kind = Literal["must", "backlog", "info"]
Polarity = Literal["coverage", "defect", "threshold", "equal"]
Tier = Literal["fast", "slow", "crm"]
Pool = Literal["cis", "tenant", "s3", "crm"]
Getter = Callable[[str, str], Any]
Num = Callable[[Getter], Optional[int]]


@dataclass(frozen=True)
class Source:
    key: str
    tier: Tier
    pool: Pool
    reads: str            # what it reads, shown on hover (table / view / listing / route), never SQL text


@dataclass(frozen=True)
class Row:
    id: str
    group: str
    label: str
    value: Num
    kind: Kind
    polarity: Polarity = "coverage"
    unit: str = "tours"
    denominator: Optional[Num] = None
    denominator_label: Optional[str] = None
    expected: Optional[Num] = None
    expected_note: Optional[str] = None
    limit: Optional[int] = None
    issue: Optional[str] = None
    drill: Optional[str] = None
    sources: tuple[str, ...] = field(default=())   # every source the row reads (for the hover text)


def f(src: str, name: str) -> Num:
    return lambda g: g(src, name)


def add(*parts: Num) -> Num:
    return lambda g: sum(int(p(g) or 0) for p in parts)


def sub(a: Num, b: Num) -> Num:
    return lambda g: int(a(g) or 0) - int(b(g) or 0)


