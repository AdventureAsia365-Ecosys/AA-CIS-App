"""AA-990 — every ISO 3166-1 country, as shared.countries holds it (CIS 279 + 288), for code that runs without a DB.

Nghiệp (S252, 27/10): a tour's country is exactly what its source says, any ISO country; each place gets its own real
country from geocoding (a tour sold as India may climb Kilimanjaro in Tanzania; a Thailand tour may sleep in Siem
Reap, Cambodia), and no hand-made "AA country" list restricts anything. This module is the ONE country list of the
CIS code: S0 (shared/country_resolver.py), the place pipeline (services/places/guards.py, shape.py, geocoder.py),
place cards, catalog.http.v1 (services/catalog_http/geo.py), AA content and the SEO country words read it.

`countries.json` is GENERATED by scripts/aa990_country_data.py from the migrations that write shared.countries
(and Natural Earth / tzdata for the derived `bbox` and `zones`); never edit it by hand. tests/unit/
test_aa990_country_mirror.py checks it against the migrations, tests/integration/test_aa990_migration_288.py against
the table itself.

Matching is the SQL resolver's (shared.country_iso2): case-insensitive, trimmed, on the name, the ISO short name, an
alias, the alpha-2 or the alpha-3 code. Every lookup key names exactly one country (279 / 288 guard).
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Optional

DATA = Path(__file__).resolve().parent / "countries.json"

# Country names / aliases that are also common words in English prose ("turkey dinner", "Phil's lodge", "a guinea
# fowl"): never read as a country by countries_named(). Resolving them as a whole value (an Excel country cell, a
# model's country answer) is not affected.
PROSE_AMBIGUOUS = frozenset({"turkey", "chad", "jordan", "georgia", "jersey", "guernsey", "guinea", "niger", "mali",
                             "phil", "panama"})
# How a compound country text joins its parts: "India and Pakistan", "Pakistan, India, China", "Nepal / Tibet",
# "Thailand & Myanmar". Never "-" (Timor-Leste, Guinea-Bissau).
_SEPARATOR = re.compile(r"\s*(?:,|/|&|;|\+|\band\b|\bor\b)\s*", re.IGNORECASE)


@dataclass(frozen=True)
class Country:
    iso2: str                       # upper case, the shared.countries key
    iso3: str
    numeric: str
    name: str                       # the canonical display name (raw_tours.country, shared.destinations.country)
    iso_name: str
    aliases: tuple[str, ...]        # lower case
    bbox: Optional[tuple[float, float, float, float]]   # (min_lat, max_lat, min_lng, max_lng), padded
    zones: tuple[tuple[str, float, float], ...]          # (IANA zone, lat, lng) from tzdata zone.tab

    def lookup_keys(self) -> set[str]:
        return {self.name.lower(), self.iso_name.lower(), self.iso2.lower(), self.iso3.lower(), *self.aliases}

    def spellings(self) -> set[str]:
        """Lower-case names a text may use for the country: name, ISO name and aliases (not the codes)."""
        return {self.name.lower(), self.iso_name.lower(), *self.aliases}


@lru_cache(maxsize=1)
def _load() -> tuple[tuple[Country, ...], dict[str, Country], dict[str, Country]]:
    raw = json.loads(DATA.read_text(encoding="utf-8"))["countries"]
    rows = tuple(Country(r["iso2"], r["iso3"], r["numeric"], r["name"], r["iso_name"], tuple(r["aliases"]),
                         tuple(r["bbox"]) if r.get("bbox") else None,
                         tuple((z[0], float(z[1]), float(z[2])) for z in r.get("zones") or ()))
                 for r in raw)
    index: dict[str, Country] = {}
    for c in rows:
        for k in c.lookup_keys():
            index.setdefault(k, c)
    return rows, index, {c.iso2: c for c in rows}


def all_countries() -> tuple[Country, ...]:
    return _load()[0]


def resolve(text: Optional[str]) -> Optional[Country]:
    """'INDIA' / ' viet nam ' / 'Tibet' / 'TZ' / 'Russia' -> the Country; None when nothing matches (a compound such as
    'India and Pakistan' included: see resolve_parts)."""
    if not isinstance(text, str):
        return None
    key = text.strip().lower()
    return _load()[1].get(key) if key else None


def by_iso2(code: Optional[str]) -> Optional[Country]:
    return _load()[2].get((code or "").strip().upper()) if code else None


def name(text: Optional[str]) -> Optional[str]:
    """The canonical name of whatever `text` names (a name, alias or code); None when unknown."""
    c = resolve(text)
    return c.name if c else None


def resolve_parts(text: Optional[str]) -> list[Country]:
    """The countries a compound text names, in order, without repeats: 'India and Pakistan' -> [India, Pakistan],
    'Pakistan, India, China' -> [Pakistan, India, China], 'Nepal / Tibet' -> [Nepal, China]. A part that is itself a
    country with a joining word in its name ('Bosnia and Herzegovina', 'Trinidad and Tobago') is kept whole: the
    longest run of parts that resolves wins. Unresolvable parts are skipped."""
    if not isinstance(text, str) or not text.strip():
        return []
    whole = resolve(text)
    if whole:
        return [whole]
    pieces, seps, pos = [], [], 0
    for m in _SEPARATOR.finditer(text):
        pieces.append(text[pos:m.start()])
        seps.append(m.group(0))
        pos = m.end()
    pieces.append(text[pos:])
    out: list[Country] = []
    i = 0
    while i < len(pieces):
        for j in range(len(pieces), i, -1):
            joined = pieces[i]
            for k in range(i + 1, j):
                joined += seps[k - 1] + pieces[k]
            c = resolve(joined)
            if c:
                if c not in out:
                    out.append(c)
                i = j
                break
        else:
            i += 1
    return out


@lru_cache(maxsize=1)
def _prose_pattern() -> tuple[re.Pattern, dict[str, Country]]:
    words: dict[str, Country] = {}
    for c in all_countries():
        for w in c.spellings():
            w = " ".join(w.replace("-", " ").split())
            if len(w) >= 4 and w not in PROSE_AMBIGUOUS:
                words.setdefault(w, c)
    alts = "|".join(re.escape(w) for w in sorted(words, key=len, reverse=True))
    return re.compile(rf"(?<![a-z0-9])(?:{alts})(?![a-z0-9])"), words


def countries_named(text: Optional[str]) -> set[str]:
    """Canonical names of the countries a prose text names, by name, ISO name or an alias of 4+ letters ('Viet Nam',
    'Burma', 'Bali', 'Tanzania'). The longest spelling wins ('North Korea' is not also 'Korea'). Codes ('IND', 'LAO')
    and the PROSE_AMBIGUOUS words are left out: in prose they are noise, not a country."""
    if not text:
        return set()
    pattern, words = _prose_pattern()
    low = " ".join(text.lower().replace("-", " ").split())
    return {words[m.group(0)].name for m in pattern.finditer(low)}
