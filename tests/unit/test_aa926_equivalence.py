"""AA-926 — the Quality System v1 registry refactor changes no gate outcome.

The fixture was generated by `python -m scripts.quality.snapshot_gate_outcomes --write` on the harness-only
commit (before any literal moved to `services/quality/`). This test recomputes the snapshot through the real
gate functions and requires it to be byte-identical. Never regenerate the fixture to make a refactor pass.

An intentional gate-behaviour change (e.g. AA-924, AA-925, Writing Memory) is the one legitimate reason to
regenerate: run `python -m scripts.quality.snapshot_gate_outcomes --write` on the commit that makes the
behaviour change (not on a later refactor commit), commit the fixture in that same commit, and say in the PR
which sections of the snapshot changed and why. Locally, run it with a dummy `AWS_PROFILE` and
`AWS_EC2_METADATA_DISABLED=true`: the script imports the api routers, whose Sentry DSN lookup otherwise
prompts for MFA."""
import json

from scripts.quality import snapshot_gate_outcomes as snap


def test_gate_outcomes_byte_identical_to_pre_refactor_snapshot():
    expected = snap.FIXTURE.read_text(encoding="utf-8")
    actual = snap.dumps(snap.build())
    if actual != expected:
        exp, act = json.loads(expected), json.loads(actual)
        diff = sorted(k for k in set(exp) | set(act) if exp.get(k) != act.get(k))
        raise AssertionError(f"gate outcomes changed in sections {diff}; see scripts/quality/snapshot_gate_outcomes.py")


def test_snapshot_is_stable_across_runs():
    assert snap.dumps(snap.build()) == snap.dumps(snap.build())


def test_snapshot_covers_all_40_fault_set_cases_and_8_channels():
    data = json.loads(snap.FIXTURE.read_text(encoding="utf-8"))
    assert len(data["t10"]["cases"]) == 40
    order = data["t10"]["channel_gate_order"]
    assert len(order["blog"]) == 25 and len(order["linkedin"]) == 24
    assert all(len(order[c]) == 23 for c in order if c not in ("blog", "linkedin"))
