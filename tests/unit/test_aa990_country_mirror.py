"""AA-990 — shared/countries (the in-code mirror of shared.countries) drifts from nothing.

Nghiệp (S252): a tour's country is what its source says, any ISO 3166-1 country; each place gets its own real
country; no hand-made "AA country" list restricts anything. shared/countries/countries.json is generated by
scripts/aa990_country_data.py from the migrations that write shared.countries (279's VALUES, 288's aliases). These
checks fail when the JSON and the migrations part ways, when a lookup key names two countries, when a country the
pipeline may meet cannot be used by the place guards, or when the polygon file outgrows its budget. The DB side (the
table after 279 + 288 equals the JSON, and shared.country_iso2 agrees with resolve) is
tests/integration/test_aa990_migration_288.py.
"""
from __future__ import annotations

import importlib.util
import json
import re
from pathlib import Path
from zoneinfo import ZoneInfo

import pytest

from shared import countries
from shared.country_resolver import COUNTRY_MASTER

REPO = Path(__file__).resolve().parents[2]
MIGRATIONS = REPO / "api" / "migrations"
POLYGONS = REPO / "services" / "places" / "geodata" / "country_polygons.json"
POLYGON_BUDGET_BYTES = 4_000_000
# Country spellings met in sources and on Dev (raw_tours history, geo.place_name, place cards; S252 read-only check).
DEV_SPELLINGS = {
    "Russia": "RU", "Tanzania": "TZ", "Kazakhstan": "KZ", "North Korea": "KP", "Bangladesh": "BD",
    "Cambodia": "KH", "Tibet": "CN", "Okinawa": "JP", "SRI-LANDKA": "LK", "Singapore": "SG", "Maldives": "MV",
    "Viet Nam": "VN", "Burma": "MM", "Korea": "KR", "Lao PDR": "LA", "Turkey": "TR",
}


def _generator():
    spec = importlib.util.spec_from_file_location("aa990_country_data", REPO / "scripts" / "aa990_country_data.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


GEN = _generator()


def test_the_mirror_equals_the_migrations():
    rows = {r["iso2"]: r for r in GEN.iso_rows(MIGRATIONS)}
    assert len(rows) == 249
    got = {c.iso2: c for c in countries.all_countries()}
    assert set(got) == set(rows)
    for code, r in rows.items():
        c = got[code]
        assert (c.iso3, c.numeric, c.name, c.iso_name) == (r["iso3"], r["numeric"], r["name"], r["iso_name"]), code
        assert sorted(c.aliases) == sorted(r["aliases"]), code


def test_288_adds_the_s0_spellings():
    added = dict(GEN.alias_additions(MIGRATIONS))
    assert added == {"CN": ["prc"], "ID": ["bali"], "JP": ["japanese"], "KH": ["khmer"],
                     "LK": ["sri landka", "srilanka"], "PH": ["phil"], "TH": ["thai"]}
    # every spelling S0 knew resolves now (as the SQL resolver does after 288), to the same country
    for canonical, spellings in COUNTRY_MASTER.items():
        expected = countries.resolve(canonical)
        assert expected is not None, canonical
        for s in spellings:
            assert countries.resolve(s) == expected, s


def test_every_lookup_key_names_one_country():
    """279 / 288 guard 2: a key that named two countries would make shared.country_iso2 depend on ORDER BY."""
    seen: dict[str, str] = {}
    for c in countries.all_countries():
        for k in c.lookup_keys():
            assert seen.setdefault(k, c.iso2) == c.iso2, (k, seen[k], c.iso2)
            assert k == k.lower()


@pytest.mark.parametrize("text, code", sorted(DEV_SPELLINGS.items()))
def test_dev_spellings_resolve(text, code):
    assert countries.resolve(text).iso2 == code
    assert countries.resolve(f"  {text.upper()} ").iso2 == code


def test_every_tour_country_ever_allowed_is_a_name():
    """Every name chk_raw_tours_country ever allowed (150, 197, 281) is a shared.countries name: 288's FK accepts every
    existing tour as it is (no tour's country changes)."""
    names = {c.name for c in countries.all_countries()}
    for path in MIGRATIONS.glob("[0-9][0-9][0-9]_*.sql"):
        sql = path.read_text(encoding="utf-8")
        for m in re.finditer(r"chk_raw_tours_country\W+CHECK\b", sql):
            start = sql.index("ARRAY[", m.end())
            listed = set(re.findall(r"'([A-Z][A-Za-z ]+)'", sql[start:sql.index("]", start)]))
            assert listed <= names, (path.name, listed - names)      # (288's comments name it with no list)


def test_every_country_is_usable_by_the_place_guards():
    from services.catalog_http import geo
    from services.places import geocoder as gc
    from services.places import guards
    from services.places import shape
    with_polygon = set(shape.country_isos())
    for c in countries.all_countries():
        code = c.iso2.lower()
        assert guards.canonical_country(c.name) == c.name
        assert guards.canonical_country(c.name.upper()) == c.name
        assert guards.iso2(c.name) == code and guards.ISO2_COUNTRY[code] == c.name
        assert guards.ISO2_ISO3[code] == c.iso3
        assert gc.GeoapifyGeocoder.params("x", code)["filter"] == f"countrycode:{code}"
        assert geo.country_code(c.name) == c.iso2
        if code in with_polygon:
            assert c.bbox is not None and code in guards.BBOX, code
    # Natural Earth draws every ISO code (admin-0 + map units for the overseas ones)
    assert with_polygon == {c.iso2.lower() for c in countries.all_countries()}


def test_bbox_shape_and_the_tuned_boxes_are_kept():
    for c in countries.all_countries():
        lo_lat, hi_lat, lo_lng, hi_lng = c.bbox
        assert -90 <= lo_lat < hi_lat <= 90 and -180 <= lo_lng < hi_lng <= 180, c.iso2
    for code, box in GEN.BBOX_TUNED.items():
        assert countries.by_iso2(code).bbox == box, code


def test_zones_exist_in_tzdata():
    missing = []
    for c in countries.all_countries():
        for zone, lat, lng in c.zones:
            ZoneInfo(zone)
            assert -90 <= lat <= 90 and -180 <= lng <= 180
        if not c.zones:
            missing.append(c.iso2)
    assert set(missing) <= {"BV", "HM"}, missing           # uninhabited: no zone in zone.tab


def test_polygon_file_stays_in_budget_and_parses_lazily():
    assert POLYGONS.stat().st_size <= POLYGON_BUDGET_BYTES
    doc = json.loads(POLYGONS.read_text(encoding="utf-8"))
    assert all(isinstance(v, str) for v in doc["countries"].values())     # one string per country: lazy parse


def test_compound_texts_split_into_iso_countries():
    def names(t):
        return [c.name for c in countries.resolve_parts(t)]
    assert names("India and Pakistan") == ["India", "Pakistan"]
    assert names("Pakistan, India, China") == ["Pakistan", "India", "China"]
    assert names("Nepal and China") == ["Nepal", "China"]
    assert names("Thailand and Myanmar") == ["Thailand", "Myanmar"]
    assert names("Nepal / Tibet") == ["Nepal", "China"]
    assert names("India & Nepal & India") == ["India", "Nepal"]
    assert names("Bosnia and Herzegovina and Serbia") == ["Bosnia and Herzegovina", "Serbia"]
    assert names("Timor-Leste") == ["Timor-Leste"]
    assert names("Kilimanjaro") == [] and names("") == [] and names(None) == []
    assert countries.resolve("India and Pakistan") is None


def test_countries_named_in_prose():
    assert countries.countries_named("Climb Mount Kilimanjaro in Tanzania") == {"Tanzania"}
    assert countries.countries_named("From North Korea's border to Viet Nam") == {"North Korea", "Vietnam"}
    assert countries.countries_named("A turkey dinner with Phil in Jordan") == set()
    assert countries.countries_named("Indian food in the IND district") == set()
    assert countries.countries_named(None) == set()
